"""Target boundaries. Protocols describe future services, not working features."""
from pathlib import Path
from typing import Protocol

class AudioRecorder(Protocol):
    def start(self, session_id: str, device_id: int) -> None: ...
    def pause(self) -> None: ...
    def resume(self) -> None: ...
    def stop(self) -> Path: ...

class Transcriber(Protocol):
    def transcribe(self, normalized_audio: Path, model: Path, device: str) -> dict: ...

class SpeakerDiarizer(Protocol):
    def diarize(self, normalized_audio: Path, model: Path, device: str) -> dict: ...

class Summarizer(Protocol):
    def draft(self, corrected_sources: dict, model: Path, device: str) -> dict: ...

class HardwareProbe(Protocol):
    def inventory(self) -> dict: ...
    def probe_engine(self, engine: str, device: str) -> dict: ...

class DocumentExporter(Protocol):
    def export(self, revision_id: str, review_id: str, destination: Path) -> Path: ...

class JobManager(Protocol):
    def enqueue(self, session_id: str, kind: str, payload: dict) -> str: ...
    def cancel(self, job_id: str) -> None: ...
